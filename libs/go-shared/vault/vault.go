// Memory is an in-process Store for tests.
//
// It enforces the SAME ownership rule as the real client, deliberately: a fake
// that skips the check would let a cross-tenant test pass while the product is
// vulnerable, which is worse than having no test.
type Memory struct {
	mu   sync.Mutex
	data map[string]map[string]string
}

func NewMemory() *Memory {
	return &Memory{data: make(map[string]map[string]string)}
}

func (m *Memory) Put(_ context.Context, ref Ref, data map[string]string) (string, error) {
	path, err := ref.Path()
	if err != nil {
		return "", err
	}
	m.mu.Lock()
	defer m.mu.Unlock()

	cp := make(map[string]string, len(data))
	for k, v := range data {
		cp[k] = v
	}
	m.data[path] = cp
	return path, nil
}

func (m *Memory) Get(_ context.Context, ref Ref, stored string) (map[string]string, error) {
	path, err := checkOwnership(ref, stored)
	if err != nil {
		return nil, err
	}
	m.mu.Lock()
	defer m.mu.Unlock()

	v, ok := m.data[path]
	if !ok {
		return nil, ErrNotFound
	}
	cp := make(map[string]string, len(v))
	for k, val := range v {
		cp[k] = val
	}
	return cp, nil
}

func (m *Memory) Delete(_ context.Context, ref Ref, stored string) error {
	path, err := checkOwnership(ref, stored)
	if err != nil {
		return err
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	delete(m.data, path)
	return nil
}

func (m *Memory) Ping(context.Context) error { return nil }

// Contains reports whether a raw value appears anywhere in the store. Tests use
// it to assert a token reached Vault and not the database.
func (m *Memory) Contains(value string) bool {
	m.mu.Lock()
	defer m.mu.Unlock()
	for _, secret := range m.data {
		for _, v := range secret {
			if v == value {
				return true
			}
		}
	}
	return false
}
